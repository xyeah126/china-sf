# ---------------- 接线逻辑 ----------------
def wire(slug: str, img_name: str) -> bool:
    """把 public/covers/<img_name> 接线到 zh+en 两个 frontmatter"""
    changed = []
    for lang in ("zh", "en"):
        path = f"src/content/works/{lang}/{slug}.md"
        if not os.path.exists(path):
            print(f"  ! 跳过（文件不存在）{path}")
            continue
        txt = open(path, encoding="utf-8").read()
        m = re.match(r"^---\n(.*?)\n---", txt, re.S)
        if not m:
            print(f"  ! 跳过（无 frontmatter）{path}")
            continue
        fm = m.group(1)
        cover_line = f'cover: "/covers/{img_name}"'

        if re.search(r"^cover:", fm, re.M):
            fm = re.sub(r"^cover:.*$", cover_line, fm, count=1, flags=re.M)
        else:
            # 插到 coverCredit 之后；没有则插到最前面
            if re.search(r"^coverCredit:", fm, re.M):
                fm = re.sub(
                    r"^coverCredit:.*$",
                    lambda mo: mo.group(0) + "\n" + cover_line,
                    fm,
                    count=1,
                    flags=re.M,
                )
            else:
                fm = cover_line + "\n" + fm

        # 统一标注为 AI 生成
        if re.search(r"^coverCredit:", fm, re.M):
            fm = re.sub(r"^coverCredit:.*$", 'coverCredit: "ai-generated"', fm, count=1, flags=re.M)
        else:
            fm = 'coverCredit: "ai-generated"\n' + fm

        new_txt = "---\n" + fm + "\n---" + txt[len(m.group(0)):]
        open(path, "w", encoding="utf-8").write(new_txt)
        changed.append(path)
    print(f"  ✓ {slug} → {img_name}  ({len(changed)} 文件)")
    return len(changed) > 0


def wire_all() -> None:
    """自动扫描 public/covers 下所有文件，按 slug 配对并接线"""
    files = os.listdir("public/covers")
    done = 0
    for f in sorted(files):
        stem = os.path.splitext(f)[0]
        if stem in PROMPTS:
            # 已接线则跳过
            p = f"src/content/works/zh/{stem}.md"
            if os.path.exists(p) and f'/covers/{f}' in open(p, encoding="utf-8").read():
                print(f"  = {stem} 已接线")
                continue
            if wire(stem, f):
                done += 1
    print(f"\n接线完成 {done} 部；提示词台账共 {len(PROMPTS)} 条")


if __name__ == "__main__":
    if len(sys.argv) >= 4 and sys.argv[1] == "wire":
        wire(sys.argv[2], sys.argv[3])
    elif len(sys.argv) >= 2 and sys.argv[1] == "wire-all":
        wire_all()
    else:
        print(f"提示词台账：{len(PROMPTS)} 条")
        print("用法: python scripts/ai_cover_prompts.py wire <slug> <文件名> | wire-all")
